const KEYS = Object.keys(DICT).sort((a, b) => b.length - a.length);

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Longest key first so "Day 7 tally" wins over a shorter "Day" key.
const RX = new RegExp(KEYS.map(escapeRe).join("|"), "g");

const ATTRS = ["title", "aria-label", "placeholder", "alt"];

function translate(text) {
  if (!text || LANG !== "zh") return text;
  return text.replace(RX, (m) => (Object.prototype.hasOwnProperty.call(DICT, m) ? DICT[m] : m));
}

function walk(node) {
  if (node.nodeType === 3) {
    const s = node.nodeValue;
    if (!s || !/[A-Za-z]/.test(s)) return;
    const out = translate(s);
    if (out !== s) node.nodeValue = out;
    return;
  }
  if (node.nodeType !== 1) return;
  const tag = node.tagName;
  if (tag === "SCRIPT" || tag === "STYLE" || tag === "CANVAS") return;
  // Static labels in index.html carry their Chinese form directly: text-node level
  // substitution can't handle "Deck <b>3</b>" because the number is inside the node.
  if (node.hasAttribute && node.hasAttribute("data-zh")) {
    node.textContent = node.getAttribute("data-zh");
    return;
  }
  for (const name of ATTRS) {
    const v = node.getAttribute && node.getAttribute(name);
    if (!v) continue;
    const out = translate(v);
    if (out !== v) node.setAttribute(name, out);
  }
  for (let i = 0; i < node.childNodes.length; i++) walk(node.childNodes[i]);
}

export const LANG = (() => {
  try {
    return localStorage.getItem("lang") === "zh" ? "zh" : "en";
  } catch (e) {
    return "en";
  }
})();

export function t(s) {
  if (LANG !== "zh") return s;
  return Object.prototype.hasOwnProperty.call(DICT, s) ? DICT[s] : translate(s);
}

// Translate a rendered subtree in place. Idempotent: Chinese output contains no
// English keys, so a second pass is a no-op.
export function localize(root) {
  if (LANG !== "zh" || !root) return;
  walk(root);
}

export function setLang(next) {
  try {
    localStorage.setItem("lang", next === "zh" ? "zh" : "en");
  } catch (e) { /* private mode: just reload without persisting */ }
  location.reload();
}

export function toggleLang() {
  setLang(LANG === "zh" ? "en" : "zh");
}

// Small round-tripping label for the header / title screen.
export function langLabel() {
  return LANG === "zh" ? "EN" : "中文";
}
